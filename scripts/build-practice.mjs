import { build } from 'esbuild';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const mocks = {
  express: `const app=()=>({use(){},get(){}});app.static=()=>()=>{};module.exports=app;`,
  http: `exports.createServer=()=>({listen(){},close(){}});`,
  os: `exports.networkInterfaces=()=>({});`,
  path: `exports.join=(...p)=>p.join('/');`,
  qrcode: `exports.toString=async()=>'';`,
  'socket.io': `exports.Server=class {constructor(){this.sockets={sockets:new Map()}} on(){} to(){return {emit(){}}}};`
};
await build({
  entryPoints: [path.join(root, 'scripts/practice-worker.cjs')],
  outfile: path.join(root, 'client/src/practice/engine-worker.js'),
  bundle: true, platform: 'browser', format: 'iife', minify: true,
  banner: { js: '// Generated by npm run build:practice from the current server rules.' },
  define: { 'process.env.PORT': '"3000"', 'process.env.TUMBLEKIN_DEV_TOOLS': '"0"',
    'process.env.TUMBLEKIN_VERBOSE': '"0"', 'require.main': 'undefined', '__dirname': '"/practice"' },
  plugins: [{ name: 'practice-only', setup(b) {
    b.onResolve({ filter: /^(express|http|os|path|qrcode|socket\.io)$/ }, args => ({ path: args.path, namespace: 'practice' }));
    b.onLoad({ filter: /.*/, namespace: 'practice' }, args => ({ contents: mocks[args.path], loader: 'js' }));
  } }]
});
console.log('Practice Worker built from the current rules.');
