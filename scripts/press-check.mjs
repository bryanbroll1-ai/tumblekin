 await page.keyboard.up('Space');await page.waitForFunction(()=>!window.__tumblekinScene.holding);
 await page.keyboard.down('Enter');await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
 await page.waitForFunction(()=>!window.__tumblekinScene.holding);
 await page.keyboard.up('Enter');
 console.log('✓ Halteknopf: echte Tastaturhaltung, Loslassen und Unterbrechung');
 await backToLobby(page);await prepare('leuchtfolge');
 await page.waitForSelector('[data-memory-pad]:not(:disabled)');
