 await page.waitForTimeout(150);
 assert.equal(await pressed('[data-pump]'),false);
 await page.locator('[data-pump]').evaluate(button=>button.click());
 assert.equal(await page.evaluate(()=>window.__tumblekinScene.localPumps),before+2,'Assistive click aktiviert die Spielaktion');
 await page.keyboard.down('Enter');await page.keyboard.down('Enter');await page.keyboard.up('Enter');
