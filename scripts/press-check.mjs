 await page.emulateMedia({reducedMotion:'no-preference'});
 console.log('✓ Pumpen: Tastatur, assistive Aktivierung, Bühne, Fensterwechsel, reduzierte Bewegung');
 // Die Fehlermeldung durchläuft das echte Netzwerk und den normalen Spieleingang.
 await page.waitForTimeout(200);
 const error=await page.evaluate(async()=>{try{await window.__tumblekinScene.sendInput({action:'unbekannt'});}catch(error){return error.message;}});
 assert.ok(error);assert.equal(await page.locator('#toast').textContent(),error);
 console.log('✓ Serverfehler wird sichtbar und nicht still geschluckt');
 await backToLobby(page);await prepare('lichtwaechter');
 await page.focus('[data-hold-run]');await page.keyboard.down('Space');
