 const stagePressed=await page.evaluate(()=>{document.querySelector('canvas.kinetic-webgl').dispatchEvent(new PointerEvent('pointerdown',{pointerId:33,pointerType:'touch',button:0,bubbles:true,cancelable:true}));return document.querySelector('[data-pump]').classList.contains('is-pressed');});
 assert.equal(stagePressed,true,'Tippen auf die Bühne drückt denselben Knopf');
 await pointer('body','pointerup',33);
 await page.waitForTimeout(160);
 await pointer('[data-pump]','pointerdown',44);
 await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
 assert.equal(await pressed('[data-pump]'),false,'Fensterwechsel beendet den Druck');
 await page.emulateMedia({reducedMotion:'reduce'});
 await pointer('[data-pump]','pointerdown',45);
 assert.equal(await page.locator('[data-pump]').evaluate(el=>getComputedStyle(el).transform),'none','Reduzierte Bewegung verwendet den Schatten ohne Verschiebung');
